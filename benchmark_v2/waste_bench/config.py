"""RunConfig: every option of a benchmark run in one place, plus run_tag()."""

from dataclasses import dataclass, field, asdict

from .constants import BACKBONES

# protocols that have a labelled validation split distinct from their test set.
# cross_domain joins them: manifest_v2 gives the wild domain a photo-grouped
# val split, so P2 selects its epoch on wild/val instead of the test set.
PROTOCOLS_WITH_VAL = ("in_domain", "joint", "cross_domain")

UNFREEZE_LEVELS = ["auto", "none", "last", "stage", "two_stages", "all"]


@dataclass
class RunConfig:
    # --- data / protocol
    manifest: str = "manifest_v2.csv"   # v2: photo-grouped wild split (benchmark_v2/make_manifest_v2.py)
    protocol: str = "cross_domain"
    backbones: list = field(default_factory=lambda: list(BACKBONES))
    select_on: str = "auto"          # auto | val | test  (which split picks the best epoch)

    # --- model
    finetune_head: bool = False      # MLP head (+ unfreeze "last" unless --unfreeze says otherwise)
    head_hidden: list = None         # custom head hidden widths, e.g. [512, 256]
    head_dropout: float = 0.3        # dropout inside the custom head
    unfreeze: str = "auto"           # see UNFREEZE_LEVELS / models/backbones.py
    freeze_bn: bool = False          # keep BatchNorm of frozen layers in eval mode
    ecoc_head: bool = False
    ecoc_codebook: str = "ordinal"

    # --- optimisation
    epochs: int = 15
    bs: int = 32
    lr: float = 3e-4
    lr_schedule: str = "cosine"
    backbone_lr_mult: float = 1.0    # lr multiplier for unfrozen backbone layers vs. the head
    label_smoothing: float = 0.0
    class_weighted: bool = False
    patience: int = None
    monitor: str = "val_loss"        # val_loss | val_f1  (early-stopping criterion)
    aug_mode: str = "auto"           # auto | off | mild | strong
    seed: int = 42
    amp: bool = False                # mixed precision (speed only)
    workers: int = 2                 # DataLoader worker processes (speed only)

    # --- evaluation
    tta: bool = False                # average predictions over image + horizontal flip

    # --- outputs
    runs_dir: str = "benchmark_v2/runs"
    out: str = None
    report_dir: str = None
    log_file: str = None
    ckpt_dir: str = None
    no_report: bool = False
    no_ckpt: bool = False

    # ---------------------------------------------------------------- derived
    def resolved_aug_mode(self):
        if self.aug_mode == "auto":
            return "mild" if self.protocol == "in_domain" else "strong"
        return self.aug_mode

    def resolved_select_on(self):
        """Which split chooses the best epoch. 'auto' uses the held-out val
        split whenever the protocol has one; the test set is only ever used
        for the final number. Under manifest_v2, cross_domain has a wild val
        split (photo-grouped if generated by make_manifest_v2.py), so test
        selection is impossible by default."""
        if self.select_on != "auto":
            return self.select_on
        return "val" if self.protocol in PROTOCOLS_WITH_VAL else "test"

    def resolved_unfreeze(self):
        if self.unfreeze != "auto":
            return self.unfreeze
        return "last" if self.finetune_head else "none"

    def to_dict(self):
        d = asdict(self)
        d["aug_mode_resolved"] = self.resolved_aug_mode()
        d["select_on_resolved"] = self.resolved_select_on()
        d["unfreeze_resolved"] = self.resolved_unfreeze()
        return d


def _fmt_float(x):
    return f"{x:.0e}".replace("e-0", "e-").replace("e+0", "e")


def run_tag(cfg: RunConfig):
    """Unique, self-describing folder name built from the options that change a
    run's outcome. Every suffix is added only when the option differs from its
    default, so runs made before an option existed keep their old folder name.
    --epochs/--patience/--amp are deliberately not part of the tag."""
    parts = [cfg.protocol, f"aug-{cfg.resolved_aug_mode()}"]
    if cfg.finetune_head:
        parts.append("ft")
    if cfg.head_hidden:
        parts.append("h" + "-".join(str(h) for h in cfg.head_hidden))
        if cfg.head_dropout != 0.3:
            parts.append(f"hd{cfg.head_dropout:g}")
    if cfg.unfreeze != "auto":
        parts.append(f"uf-{cfg.unfreeze}")
    if cfg.class_weighted:
        parts.append("cw")
    if cfg.ecoc_head:
        parts.append("ecoc" if cfg.ecoc_codebook == "ordinal" else f"ecoc-{cfg.ecoc_codebook}")
    if cfg.freeze_bn:
        parts.append("fbn")
    if cfg.lr_schedule != "cosine":
        parts.append(f"lr-{cfg.lr_schedule}")
    if cfg.lr != 3e-4:
        parts.append(f"lr{_fmt_float(cfg.lr)}")
    if cfg.backbone_lr_mult != 1.0:
        parts.append(f"blr{cfg.backbone_lr_mult:g}")
    if cfg.bs != 32:
        parts.append(f"bs{cfg.bs}")
    if cfg.label_smoothing:
        parts.append(f"ls{cfg.label_smoothing:g}")
    if cfg.monitor != "val_loss":
        parts.append("mon-f1")
    if cfg.select_on != "auto":
        parts.append(f"sel-{cfg.select_on}")
    if cfg.tta:
        parts.append("tta")
    if cfg.seed != 42:
        parts.append(f"s{cfg.seed}")
    return "_".join(parts)
